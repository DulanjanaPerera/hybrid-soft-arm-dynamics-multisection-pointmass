function [pressureCommand_bar,tauRequested_N,tauEquivalent_N, ...
 allocationResidual_N,s_mPerS,inertiaForce_N,coriolisForce_N, ...
 dampingForce_N,staticForce_N,feedbackForce_N,modelValid,limited, ...
 status,allAboveActivation,anchorReady,forceBias_N,tauBlended_N, ...
 stiffnessEstimate_NPerM,dampingEstimate_NsPerM,hysteresisForce_N, ...
 adaptiveBias_N,parameterEstimate,historyState,adaptationActive, ...
 parameterAtBound,adaptiveForce_N] = pacAdaptiveCommonPressureBlock( ...
 measured,desired,gravity_arm,measurementValid,baseValid,measurementTime_s, ...
 t,enablePressure,lambda,dampingGain,enableAdaptation)
%#codegen
% Paste into NEW controller block; Discrete .05 s. Existing first 8 inputs
% and first 17 outputs preserved. New inputs: lambda 2x1, Ks 2x1, adapt boolean.
% Estimates correspond to force evaluation; updates take effect NEXT sample.
persistent ps as
if isempty(ps),ps=pacPressureInitialState();as=pacAdaptiveInitialState();end
cfg=pacAdaptiveConfig();pc=pacPressureConfig();
good=measurementValid && baseValid && isfinite(measurementTime_s) && ...
 isfinite(t) && measurementTime_s<=t+1e-9 && ...
 t-measurementTime_s<=pc.maxSampleAge_s+1e-9;
dt=0;
if good && measurementTime_s>as.lastSample
 if as.lastSample>=0,dt=measurementTime_s-as.lastSample;end
 if all(isfinite(measured(:))) && ~ps.fault
  as.z=pacAdaptiveHistory(as.z,measured(3:4),dt);
 end
 as.lastSample=measurementTime_s;
end
[tauRequested_N,s_mPerS,Y,inertiaForce_N,coriolisForce_N, ...
 dampingForce_N,staticForce_N,feedbackForce_N,hysteresisForce_N, ...
 adaptiveBias_N,stiffnessEstimate_NPerM,dampingEstimate_NsPerM,modelValid]= ...
 pacAdaptiveForce(measured,desired,gravity_arm,lambda,dampingGain,as,good);
% Capture nominal static+history+bias consistently with current model at trim.
[pressureCommand_bar,tauEquivalent_N,allocationResidual_N,limited,status, ...
 allAboveActivation,tauBlended_N,ps]=pacPressureStep(tauRequested_N, ...
 staticForce_N+hysteresisForce_N+adaptiveBias_N,measured(3:4),modelValid, ...
 measurementTime_s,t,enablePressure,pc,ps);
anchorReady=ps.anchorReady;forceBias_N=ps.forceBias;
parameterEstimate=as.theta;historyState=as.z;
[p,~,~]=pacNominalParameters(gravity_arm);
q=measured(1:2);v=desired(3:4)-lambda(:).*(q-desired(1:2));
adaptiveForce_N=(stiffnessEstimate_NPerM-p.K)*q+ ...
 (dampingEstimate_NsPerM-p.D)*v+hysteresisForce_N+adaptiveBias_N;
allow=enableAdaptation && good && modelValid && status==uint8(3) && ...
 ~limited && all(isfinite(allocationResidual_N)) && ...
 norm(allocationResidual_N)<=cfg.residualTolerance_N;
[as,adaptationActive,parameterAtBound]=pacAdaptiveUpdate(as,Y,s_mPerS,dt,allow);
end
