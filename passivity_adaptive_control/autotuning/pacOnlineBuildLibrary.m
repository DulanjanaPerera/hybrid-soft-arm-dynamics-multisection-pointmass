function pacOnlineBuildLibrary(configFile,outputFile)
%PACONLINEBUILDLIBRARY Build a NEW standalone library, never load arm models.
% The output can be copied into a user-created model duplicate.
assert(isfile(configFile)&&~isfile(outputFile));
[~,name]=fileparts(outputFile);assert(isvarname(name));
assert(~bdIsLoaded(name),'Close an existing library with this name first.');
configFile=char(java.io.File(configFile).getCanonicalPath());
configFile=strrep(configFile,'''','''''');
new_system(name,'Library');cleanup=onCleanup(@()close_system(name,0)); %#ok<NASGU>
set_param(name,'Lock','off');
b=[name '/Online controller'];add_block('simulink/User-Defined Functions/MATLAB Function',b, ...
    'Position',[70 80 330 310]);
script=sprintf([ ...
    'function [theta,phi,k_g,d_g,h_g,pressureEnable,adaptationEnable,phase,candidateId,done,reason,metrics] = onlineController(u,actualGamma,settings,networkEnable)\n' ...
    '%%#codegen\n' ...
    'coder.extrinsic(''pacOnlineUdpBridge'');\n' ...
    'data=coder.load(''%s'',''rt''); c=data.rt;\n' ...
    'persistent state\n' ...
    'if isempty(state),state=pacOnlineInitialState(c);end\n' ...
    'rx=zeros(7,1);\n' ...
    '%% Transmit the complete previous sample, keeping all timestamps aligned.\n' ...
    'persistent packet\n' ...
    'if isempty(packet),packet=zeros(121,1);packet(1)=c.session;packet(5)=-1;end\n' ...
    'if networkEnable,rx=pacOnlineUdpBridge(packet,c.blockPort,c.workerPort,c.session);end\n' ...
    '[state,y,header]=pacOnlineRuntimeStep(state,u,actualGamma,settings,rx,c);\n' ...
    'packet=[header;u;y(1:2);actualGamma;settings];\n' ...
    'theta=y(1);phi=y(2);k_g=y(3);d_g=y(4);h_g=y(5);\n' ...
    'pressureEnable=y(6);adaptationEnable=y(7);\n' ...
    'phase=y(8);candidateId=y(9);done=y(10);reason=y(11);metrics=y(12:15);\n' ...
    'end\n'],configFile);
r=sfroot;chart=r.find('-isa','Stateflow.EMChart','Path',b);chart.Script=script;
chart.ChartUpdate='DISCRETE';chart.SampleTime='0.05';
setsize(chart,'u','[12 1]');setsize(chart,'actualGamma','[10 1]');
setsize(chart,'settings','[81 1]');setsize(chart,'metrics','[4 1]');
b=[name '/Settings vector'];add_block('simulink/User-Defined Functions/MATLAB Function',b, ...
    'Position',[440 80 700 310]);
chart=r.find('-isa','Stateflow.EMChart','Path',b);
chart.Script=sprintf([ ...
    'function settings = packSettings(scale,rate,lower,upper,initial,options,history,pressure,supervisor,lambda,Ks,mechanicalEnable,commonEnable,freezeHysteresis)\n' ...
    '%%#codegen\n' ...
    'settings=pacOnlineSettingsVector(scale,rate,lower,upper,initial,options,history,pressure,supervisor,lambda,Ks,mechanicalEnable,commonEnable,freezeHysteresis);\n' ...
    'end\n']);
for n={'scale','rate','lower','upper','initial'},setsize(chart,n{1},'[10 1]');end
setsize(chart,'options','[3 1]');setsize(chart,'history','[4 1]');
setsize(chart,'pressure','[10 1]');setsize(chart,'supervisor','[7 1]');
setsize(chart,'lambda','[2 1]');setsize(chart,'Ks','[2 1]');setsize(chart,'settings','[81 1]');
set_param(name,'Lock','on');save_system(name,outputFile);
fprintf('Built standalone library: %s\nNo hardware model was opened.\n',outputFile);
end
function setsize(chart,name,sz)
d=chart.find('-isa','Stateflow.Data','Name',name);d.Props.Array.Size=sz;
end
