function [pressureCommand_bar,tauRequested_N,tauEquivalent_N, ...
    allocationResidual_N,s_mPerS,inertiaForce_N,coriolisForce_N, ...
    dampingForce_N,staticForce_N,feedbackForce_N,modelValid,limited, ...
    status,allAboveActivation,anchorReady,forceBias_N,tauBlended_N] = ...
    pacCommonPressureBlock(measured,desired,gravity_arm,measurementValid, ...
    baseValid,measurementTime_s,t,enablePressure)
% New MATLAB Function block wrapper. Configure DISCRETE 0.05 s sample time.
% measured 4x1 [q;dq], desired 6x1 [qd;dqd;ddqd], gravity 3x1.
% measurementTime_s is timestamp of last genuinely successful paired poll,
% NOT Clock copied onto held data. Keep physical Kill downstream.
% No adaptation, payload, integral or hardware I/O. All force estimates are N.
% Add project root and this folder to MATLAB path. Existing models untouched.
%#codegen
persistent state
if isempty(state), state=pacPressureInitialState(); end
[tauRequested_N,s_mPerS,~,~,inertiaForce_N,coriolisForce_N, ...
    dampingForce_N,staticForce_N,feedbackForce_N,modelValid]= ...
    pacFixedBlock(measured,desired,gravity_arm,measurementValid,baseValid);
cfg=pacPressureConfig();
[pressureCommand_bar,tauEquivalent_N,allocationResidual_N,limited,status, ...
    allAboveActivation,tauBlended_N,state]=pacPressureStep( ...
    tauRequested_N,staticForce_N,measured(3:4),modelValid,measurementTime_s, ...
    t,enablePressure,cfg,state);
anchorReady=state.anchorReady; forceBias_N=state.forceBias;
end
