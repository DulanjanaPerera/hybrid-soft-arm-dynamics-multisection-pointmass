function [pressureCommand_bar,tauRequested_N,tauEquivalent_N, ...
 allocationResidual_N,s_mPerS,inertiaForce_N,coriolisForce_N, ...
 dampingForce_N,staticForce_N,feedbackForce_N,modelValid,limited, ...
 status,allAboveActivation,anchorReady,forceBias_N,tauBlended_N, ...
 stiffnessEstimate_NPerM,dampingEstimate_NsPerM,hysteresisForce_N, ...
 adaptiveBias_N,parameterEstimate,historyState,adaptationActive, ...
 parameterAtBound,adaptiveForce_N,commonPressure_bar,commonPressureShift_bar,residualDiagnostic] = pacResidualAdaptiveTunableBlock( ...
 measured,desired,gravity_arm,measurementValid,baseValid,measurementTime_s, ...
 t,enablePressure,lambda,dampingGain,enableAdaptation, ...
 enableCommonPressureAdaptation,adaptationGamma,parameterScale,parameterMaxRate, ...
 parameterLower,parameterUpper,parameterInitial,adaptationOptions, ...
 historyOptions,pressureOptions,supervisorOptions,freezeHysteresisWeights,enableResidual,residualOptions)
%#codegen
% Existing23 inputs/28 outputs preserved. Append enableResidual and8x1 options.
% The existing feedback/adaptive update stays unchanged. theta-theta0 now
% estimates remaining correction around the learned fixed-nominal model.
% Restart/reset all states before each model-off/on comparison.
network=residualControllerNetwork(residualOptions(1));residualValidateOptions(residualOptions);
[cfg,pc]=pacTuningConfig(adaptationGamma,parameterScale,parameterMaxRate, ...
 parameterLower,parameterUpper,parameterInitial,adaptationOptions, ...
 historyOptions,pressureOptions,supervisorOptions);
if freezeHysteresisWeights
 cfg.gamma(6:8)=0;
end
pc.enableCommonAdaptation=logical(enableCommonPressureAdaptation);
persistent ps as ns
if isempty(ps)
 ps=residualPressureInitialState();ns=residualNeuralInitialState();as=pacAdaptiveInitialState();as.theta=cfg.initial;
end
good=measurementValid && baseValid && isfinite(measurementTime_s) && ...
 isfinite(t) && measurementTime_s<=t+1e-9 && ...
 t-measurementTime_s<=pc.maxSampleAge_s+1e-9;
dt=0;
if good && measurementTime_s>as.lastSample
 if as.lastSample>=0,dt=measurementTime_s-as.lastSample;end
 if all(isfinite(measured(:))) && ~ps.fault
  as.z=pacAdaptiveHistory(as.z,measured(3:4),dt,cfg);
 end
 as.lastSample=measurementTime_s;
end
[tauRequested_N,s_mPerS,Y,inertiaForce_N,coriolisForce_N, ...
 dampingForce_N,staticForce_N,feedbackForce_N,hysteresisForce_N, ...
 adaptiveBias_N,stiffnessEstimate_NPerM,dampingEstimate_NsPerM,modelValid]= ...
 pacAdaptiveForce(measured,desired,gravity_arm,lambda,dampingGain,as,good);
% Anchor includes the same residual/activation/gravity definition as inversion.
shift=zeros(2,1);
if enableResidual&&modelValid,shift=residualGravityShift(measured,gravity_arm);end
[pressureCommand_bar,tauEquivalent_N,allocationResidual_N,limited,status, ...
 allAboveActivation,tauBlended_N,ps,ns,residualDiagnostic]=residualPressureStep(tauRequested_N, ...
 staticForce_N+hysteresisForce_N+adaptiveBias_N,measured,modelValid, ...
 measurementTime_s,t,enablePressure,pc,ps,ns,network,residualOptions,enableResidual,shift);
commonPressure_bar=mean(pressureCommand_bar);
commonPressureShift_bar=commonPressure_bar-pc.common_bar;
anchorReady=ps.anchorReady;forceBias_N=ps.forceBias;
parameterEstimate=as.theta;historyState=as.z;
residualDiagnostic.parameterCorrection=as.theta-[650;650;650;40;40;0;0;0;0;0];
[p,~,~]=pacNominalParameters(gravity_arm);
q=measured(1:2);v=desired(3:4)-lambda(:).*(q-desired(1:2));
adaptiveForce_N=(stiffnessEstimate_NPerM-p.K)*q+ ...
 (dampingEstimate_NsPerM-p.D)*v+hysteresisForce_N+adaptiveBias_N;
allow=enableAdaptation && good && modelValid && status==uint8(3) && ...
 ~limited && all(isfinite(allocationResidual_N)) && ...
 norm(allocationResidual_N)<=cfg.residualTolerance_N;
[as,adaptationActive,parameterAtBound]=pacAdaptiveUpdate(as,Y,s_mPerS,dt,allow,cfg);
end


